/**
 * Калькулятор числа зрелости (Maturity Number) = Число Выражения + Число Судьбы
 * Заменяет авторскую "число управления" на классическое число зрелости
 */
class ControlCalculator {
    constructor() {
        this.baseCalculator = null; // будет установлен извне
    }

    setBaseCalculator(calc) {
        this.baseCalculator = calc;
    }

    /**
     * Расчет числа зрелости
     * @param {Object} baseNumbers - базовые числа (содержит expression и lifePath)
     * @returns {Object} объект с числом и описанием
     */
    calculate(baseNumbers) {
        if (!baseNumbers.expression || !baseNumbers.lifePath) {
            return {
                number: 0,
                description: 'Недостаточно данных для расчета числа зрелости'
            };
        }

        const maturityNumber = this.baseCalculator.calculateMaturity(
            baseNumbers.expression,
            baseNumbers.lifePath
        );

        return {
            number: maturityNumber,
            description: this.getDescription(maturityNumber)
        };
    }

    getDescription(num) {
        const descriptions = {
            1: 'В зрелости вы раскроете лидерские качества и научитесь быть независимым. Ваша задача — вести за собой, не боясь быть первым.',
            2: 'В зрелости вы станете дипломатом и миротворцем. Ваша задача — создавать гармонию и учиться сотрудничеству.',
            3: 'В зрелости вы расцветете творчески. Ваша задача — делиться своим вдохновением и радостью с миром.',
            4: 'В зрелости вы построите прочный фундамент. Ваша задача — создать стабильность и порядок во всех сферах жизни.',
            5: 'В зрелости вы обретете истинную свободу. Ваша задача — принимать перемены и учиться адаптивности.',
            6: 'В зрелости вы станете опорой для близких. Ваша задача — служить и заботиться, но не забывать о себе.',
            7: 'В зрелости вы углубитесь в познание. Ваша задача — искать мудрость и делиться ею с другими.',
            8: 'В зрелости вы достигнете материального и духовного изобилия. Ваша задача — правильно распоряжаться властью и ресурсами.',
            9: 'В зрелости вы придете к мудрости завершения. Ваша задача — отпускать и завершать циклы с благодарностью.',
            11: 'В зрелости вы станете духовным учителем. Ваша задача — нести свет и вдохновение, используя свою высокую интуицию.',
            22: 'В зрелости вы воплотите великие проекты. Ваша задача — строить нечто значимое для всего человечества.',
            33: 'В зрелости вы проявите безусловную любовь. Ваша задача — исцелять и учить, неся сострадание миру.'
        };

        return descriptions[num] || this.getDefaultDescription(num);
    }

    getDefaultDescription(num) {
        return `Число зрелости ${num} — это ваш потенциал, который раскроется во второй половине жизни. Наблюдайте за своими глубинными устремлениями.`;
    }
}

module.exports = ControlCalculator;